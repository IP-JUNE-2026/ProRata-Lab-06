public class IT23692046Lab6Q2A {
    public static void main(String[] args) {
        // Initialize the counter variable
        int i = 1;

        System.out.print("Output: ");
        
        // Use a while loop to print numbers from 1 to 10
        while (i <= 10) {
            System.out.print(i + " ");
            i++;
        }
        
        // Print a new line at the end
        System.out.println();
    }
}